// In-memory per-instance rate limiter (token bucket).
// Worker instances are short-lived/sharded, so this is a soft limit
// that complements DB-backed daily quotas.

type Bucket = { count: number; resetAt: number };
const buckets = new Map<string, Bucket>();

export type RateLimitResult = {
  ok: boolean;
  remaining: number;
  resetIn: number;
};

export function rateLimit(
  key: string,
  limit: number,
  windowMs: number,
): RateLimitResult {
  const now = Date.now();
  const b = buckets.get(key);
  if (!b || b.resetAt < now) {
    buckets.set(key, { count: 1, resetAt: now + windowMs });
    return { ok: true, remaining: limit - 1, resetIn: windowMs };
  }
  b.count += 1;
  const remaining = Math.max(0, limit - b.count);
  return { ok: b.count <= limit, remaining, resetIn: b.resetAt - now };
}

// Lightweight cleanup so the map can't grow unbounded
let lastSweep = 0;
export function sweep() {
  const now = Date.now();
  if (now - lastSweep < 60_000) return;
  lastSweep = now;
  for (const [k, b] of buckets) if (b.resetAt < now) buckets.delete(k);
}
